"""Independent geometry measurements for the construction slice; all model files are read-only."""
import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / ".local/evidence/construction-20261018"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--include-ui", action="store_true")
    options = parser.parse_args()
    # Expected world bounds and per-object volumes are analytic, not generated by the kernel under test.
    expected = {
        "checks/union.3mf": ([0, 0, 0], [30, 20, 20], [12000]),
        "checks/subtract.3mf": ([0, 0, 0], [10, 20, 20], [4000]),
        "checks/intersect.3mf": ([10, 0, 0], [20, 20, 20], [4000]),
        "checks/split-both.3mf": ([-5, 0, 0], [25, 20, 20], [6000, 6000]),
        "checks/split-diagonal.3mf": ([-5, 0, 0], [25, 20, 20], [6000, 6000]),
        "checks/hollow-split.3mf": ([0, 0, 0], [20, 20, 20], [3500, 3500]),
    }
    for name in ("union", "subtract", "intersect"):
        expected[f"checks/{name}.stl"] = expected[f"checks/{name}.3mf"]
    octagon_volume = 16000 * (np.sqrt(2) - 1)
    expected["checks/rotated-union.3mf"] = ([10-10*np.sqrt(2), 10-10*np.sqrt(2), 0], [10+10*np.sqrt(2), 10+10*np.sqrt(2), 20], [16000-octagon_volume])
    expected["checks/rotated-intersect.3mf"] = ([0, 0, 0], [20, 20, 20], [octagon_volume])
    expected["checks/rotated-subtract.3mf"] = ([0, 0, 0], [20, 20, 20], [8000-octagon_volume])
    if options.include_ui:
        expected["ui-split.3mf"] = ([0, 0, 0], [20, 20, 20], [4000, 4000])
        expected["ui-subtract.3mf"] = expected["checks/subtract.3mf"]
    results = []
    for name, (low, high, volumes) in expected.items():
        scene = trimesh.load(BASE / name, force="scene", process=True)
        assert np.allclose(scene.bounds, [low, high], atol=1e-8, rtol=0), name
        parts = []
        for node in scene.graph.nodes_geometry:
            transform, geometry = scene.graph[node]
            mesh = scene.geometry[geometry].copy()
            mesh.apply_transform(transform)
            assert mesh.is_watertight and mesh.is_winding_consistent, name
            assert np.all(mesh.area_faces > 0), name
            ordered_faces = np.sort(mesh.faces, axis=1)
            assert len(np.unique(ordered_faces, axis=0)) == len(mesh.faces), name
            parts.append({"volume_mm3": float(mesh.volume), "bounds_mm": mesh.bounds.tolist(),
                          "triangles": len(mesh.faces), "watertight_after_vertex_processing": bool(mesh.is_watertight),
                          "winding_consistent": bool(mesh.is_winding_consistent), "zero_area_faces": 0, "duplicate_faces": 0})
        assert np.allclose(sorted(p["volume_mm3"] for p in parts), sorted(volumes), atol=1e-7, rtol=0), name
        assert len(parts) == len(volumes), name
        results.append({"file": name, "sha256": digest(BASE / name), "parts": parts})
    inputs = []
    for folder in ("generated", "failures"):
        directory = ROOT / "fixtures" / folder
        for case in json.loads((directory / "manifest.json").read_text())["cases"]:
            assert digest(directory / case["file"]) == case["sha256"], case["file"]
            inputs.append({"file": f"fixtures/{folder}/{case['file']}", "sha256": case["sha256"]})
    report = {"timestamp": datetime.now(timezone.utc).isoformat(), "trimesh_version": trimesh.__version__,
              "scope": "Analytic solids, individually checked after vertex processing; no general self-intersection or repair certification",
              "outputs": results, "unchanged_inputs": inputs}
    (BASE / "output-verification.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"PASS: {len(results)} construction outputs; analytic bounds/volumes, closed winding, no zero-area/duplicate faces; {len(inputs)} unchanged fixtures.")


if __name__ == "__main__":
    main()
